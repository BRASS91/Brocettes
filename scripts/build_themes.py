"""Generate themes.css: a light and a dark palette for the default look and each character.

Each theme is a few hues; this script turns them into the app's colour tokens and nudges
lightness until every text/background pair passes WCAG contrast (4.5:1 for normal text,
7:1 for body ink). Run after changing THEMES:  python3 scripts/build_themes.py
"""
import colorsys, pathlib

# The default light palette, kept identical to the tokens in app.css.
CLASSIC = {"page": "#F4EAD5", "card": "#FBF5E8", "inset": "#EFE1C4", "nav": "#EDE0C4", "rule": "#D2BC90", "rule-gold": "#C9A86A",
           "ink": "#2B1D12", "muted": "#6B5640", "red": "#7A1F12", "red-2": "#A8382A", "on-red": "#FBF5E8"}

# id: (label, paper hue, paper saturation, accent hue, accent saturation, rule hue)
THEMES = {
    "default":  ("Classic handbook", 40, 55, 8, 74, 38),
    "broc":     ("Broc",     38, 70, 22, 82, 220),
    "francis":  ("Francis",  155, 18, 170, 60, 160),
    "levon":    ("Levon",    30, 30, 214, 64, 28),
    "vexhar":   ("Vexhar",   0, 6, 354, 72, 350),
    "blue":     ("Blue",     235, 30, 248, 58, 280),
    "allyanna": ("Allyanna", 310, 30, 326, 58, 220),
    "caine":    ("Caine",    70, 28, 88, 48, 45),
}

def rgb(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, max(0, min(100, l)) / 100, max(0, min(100, s)) / 100)
    return r, g, b
def hexc(c): return "#%02X%02X%02X" % tuple(round(x * 255) for x in c)
def lum(c):
    f = lambda x: x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    r, g, b = map(f, c); return 0.2126 * r + 0.7152 * g + 0.0722 * b
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True); return (la + 0.05) / (lb + 0.05)

def fit(h, s, l, against, need, step):
    """Move lightness by step until the colour reaches `need` contrast against every background."""
    for _ in range(200):
        c = rgb(h, s, l)
        if all(contrast(c, bg) >= need for bg in against): return c
        l += step
    raise SystemExit(f"can't reach {need}:1 for hue {h}")

def palette(paper_h, paper_s, acc_h, acc_s, rule_h, dark):
    t = {}
    if not dark:
        page, card, inset, nav = rgb(paper_h, paper_s, 91), rgb(paper_h, paper_s, 96), rgb(paper_h, paper_s, 86), rgb(paper_h, paper_s, 88)
        t["rule"] = rgb(rule_h, min(paper_s + 10, 45), 70); t["rule-gold"] = rgb(rule_h, min(paper_s + 25, 55), 60)
        t["ink"] = fit(paper_h, 40, 14, [page, card, inset], 10, -1)
        t["muted"] = fit(paper_h, 22, 36, [page, card, inset], 4.6, -1)
        t["red"] = fit(acc_h, acc_s, 32, [page, card, inset], 5.5, -1)
        t["red-2"] = fit(acc_h, acc_s, 42, [page, card], 4.5, -1)
        t["on-red"] = card
        pair = lambda hue, sat: (rgb(hue, sat, 87), fit(hue, sat + 10, 28, [rgb(hue, sat, 87)], 5, -1))
    else:
        page, card, inset, nav = rgb(paper_h, min(paper_s, 22), 9), rgb(paper_h, min(paper_s, 22), 13), rgb(paper_h, min(paper_s, 22), 19), rgb(paper_h, min(paper_s, 22), 11)
        t["rule"] = rgb(rule_h, min(paper_s, 25), 30); t["rule-gold"] = rgb(rule_h, min(paper_s + 15, 45), 40)
        t["ink"] = fit(paper_h, 25, 88, [page, card, inset], 10, 1)
        t["muted"] = fit(paper_h, 14, 66, [page, card, inset], 4.6, 1)
        t["red"] = fit(acc_h, acc_s, 62, [page, card, inset], 5.5, 1)
        t["red-2"] = fit(acc_h, acc_s, 72, [page, card], 6, 1)
        t["on-red"] = fit(acc_h, 30, 8, [t["red"]], 5, -1)
        pair = lambda hue, sat: (rgb(hue, min(sat, 40), 18), fit(hue, sat, 72, [rgb(hue, min(sat, 40), 18)], 5.5, 1))
    t.update(page=page, card=card, inset=inset, nav=nav)
    t["ok-bg"], t["ok"] = pair(120, 30)
    t["claim-bg"], t["claim"] = pair(275, 30)
    t["rumour-bg"], t["rumour"] = pair(38, 60)
    t["bad-bg"], t["bad"] = pair(12, 55)
    # sanity: the pairs the app actually puts text on
    checks = [("ink", "page", 7), ("ink", "card", 7), ("muted", "card", 4.5), ("muted", "inset", 4.5), ("red", "page", 4.5),
              ("red", "inset", 4.5), ("on-red", "red", 4.5), ("ok", "ok-bg", 4.5), ("claim", "claim-bg", 4.5),
              ("rumour", "rumour-bg", 4.5), ("bad", "bad-bg", 4.5)]
    for fg, bg, need in checks:
        assert contrast(t[fg], t[bg]) >= need, (fg, bg, round(contrast(t[fg], t[bg]), 2))
    return t

ORDER = ["page", "card", "inset", "nav", "rule", "rule-gold", "ink", "muted", "red", "red-2", "on-red",
         "ok-bg", "ok", "claim-bg", "claim", "rumour-bg", "rumour", "bad-bg", "bad"]
def block(sel, t, dark):
    lines = [f"  --{k}: {hexc(t[k])};" for k in ORDER]
    lines.append(f"  --shadow: {'rgba(0, 0, 0, .5)' if dark else 'rgba(43, 29, 18, .2)'};")
    lines.append(f"  --scrim: {'rgba(0, 0, 0, .6)' if dark else 'rgba(43, 29, 18, .42)'};")
    lines.append(f"  color-scheme: {'dark' if dark else 'light'};")
    return f"{sel} {{\n" + "\n".join(lines) + "\n}"

out = ["/* Generated by scripts/build_themes.py. Edit THEMES there, not this file. */"]
swatches = {}
for tid, (label, ph, ps, ah, as_, rh) in THEMES.items():
    light, dark = palette(ph, ps, ah, as_, rh, False), palette(ph, ps, ah, as_, rh, True)
    base = ":root" if tid == "default" else f':root[data-theme="{tid}"]'
    if tid == "default":  # the classic light look stays exactly as defined in app.css
        light = {k: tuple(int(v[i:i + 2], 16) / 255 for i in (1, 3, 5)) for k, v in CLASSIC.items()}
    else:
        out.append(block(base, light, False))
    out.append(block(f'{base}[data-mode="dark"]' if tid != "default" else ':root[data-mode="dark"], :root[data-theme="default"][data-mode="dark"]', dark, True))
    swatches[tid] = {"label": label, "light": [hexc(light[k]) for k in ("page", "red", "rule-gold")], "dark": [hexc(dark[k]) for k in ("page", "red", "rule-gold")], "nav": [hexc(light["nav"]), hexc(dark["nav"])]}
root = pathlib.Path(__file__).resolve().parent.parent
(root / "themes.css").write_text("\n".join(out) + "\n")
import json
(root / "features" / "themes.json").write_text(json.dumps(swatches, indent=1) + "\n")
print(f"wrote themes.css ({len(THEMES)} themes x light/dark) and features/themes.json")
